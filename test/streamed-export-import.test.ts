import { createCipheriv, createHash } from "node:crypto";
import { createReadStream, createWriteStream } from "node:fs";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { describe, expect, it, onTestFinished } from "vitest";
import { startInstalledCronk, type Client } from "./harness.js";

/**
 * Exports and imports streamed, so Workspaces whose files add up to more than fits in memory round-trip (#209).
 * The files are generated as they are sent rather than held, and every transfer streams over real HTTP, so the
 * test's own memory stays flat and what grows is the server's.
 */

const MB = 1024 * 1024;

/** `size` bytes that don't compress, the same for the same `seed`, generated as they are read. */
function generated(seed: number, size: number): Readable {
  const cipher = createCipheriv("aes-256-ctr", Buffer.alloc(32, seed), Buffer.alloc(16));
  const zeros = Buffer.alloc(MB);
  let left = size;
  return new Readable({
    read() {
      if (left === 0) return void this.push(null);
      const n = Math.min(left, zeros.length);
      left -= n;
      this.push(cipher.update(zeros.subarray(0, n)));
    },
  });
}

/** The SHA-256 of everything `stream` gives. */
async function sha256(stream: Readable): Promise<string> {
  const hash = createHash("sha256");
  for await (const chunk of stream) hash.update(chunk as Buffer);
  return hash.digest("hex");
}

/** Everything `stream` gives, as text. */
async function text(stream: Readable): Promise<string> {
  let all = "";
  for await (const chunk of stream) all += String(chunk);
  return all;
}

/** A temporary file path, removed when the test ends. */
async function tempFile(name: string): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "cronk-streamed-"));
  onTestFinished(() => rm(dir, { recursive: true, force: true }));
  return join(dir, name);
}

/** Uploads `size` generated bytes from `seed` as an Attachment at `path`, streamed. */
async function attach(client: Client, path: string, seed: number, size: number) {
  const res = await client.send(path, { method: "POST", body: generated(seed, size), headers: { "content-type": "application/octet-stream" } });
  expect(res.statusCode).toBe(201);
  return (JSON.parse(await text(res)) as { attachment: { id: string } }).attachment;
}

/**
 * Runs `work` while sampling how many bytes of Buffers the process holds beyond what it held before, and answers
 * the most it saw. The server runs in this process, so this counts what it holds.
 */
async function peakBuffers(work: () => Promise<void>): Promise<number> {
  const held = () => process.memoryUsage().arrayBuffers;
  const before = held();
  let peak = 0;
  const sampling = setInterval(() => (peak = Math.max(peak, held() - before)), 5);
  try {
    await work();
  } finally {
    clearInterval(sampling);
  }
  return Math.max(peak, held() - before);
}

describe("a Workspace export holding more than 200 MB of Attachments", () => {
  it("is streamed out and back into a fresh installation, every Attachment downloading byte for byte", { timeout: 300_000 }, async () => {
    const { admin } = await startInstalledCronk();
    await admin.post("/api/projects", { name: "Cronk", key: "CRONK" });
    await admin.post("/api/projects/CRONK/tickets", { title: "Recordings" });
    const sizes = [75 * MB, 75 * MB, 75 * MB + 123];
    const attached = [];
    for (const [i, size] of sizes.entries()) attached.push({ ...(await attach(admin, `/api/tickets/CRONK-1/attachments?name=recording-${i}.bin`, i + 1, size)), seed: i + 1, size });

    const archive = await tempFile("export.tar.gz");
    const exportPeak = await peakBuffers(async () => {
      const res = await admin.send("/api/export");
      expect(res.statusCode).toBe(200);
      await pipeline(res, createWriteStream(archive));
    });
    // Holding even one of the files whole would take more.
    expect(exportPeak).toBeLessThan(64 * MB);

    const elsewhere = (await startInstalledCronk("Elsewhere")).admin;
    const importPeak = await peakBuffers(async () => {
      const imported = await elsewhere.send("/api/import", { method: "POST", body: createReadStream(archive), headers: { "content-type": "application/gzip" } });
      expect(imported.statusCode, await text(imported)).toBe(201);
    });
    expect(importPeak).toBeLessThan(64 * MB);

    const { attachments } = (await elsewhere.get("/api/tickets/CRONK-1/attachments")).body;
    expect(attachments.map((a: { id: string; size: number }) => [a.id, a.size])).toEqual(attached.map((a) => [a.id, a.size]));
    for (const a of attached) {
      const file = await elsewhere.send(`/api/attachments/${a.id}/file`);
      expect(file.statusCode).toBe(200);
      expect(await sha256(file)).toBe(await sha256(generated(a.seed, a.size)));
    }
    expect((await elsewhere.get("/api/workspace/storage")).body.attachments).toEqual({ files: 3, bytes: sizes.reduce((a, b) => a + b) });
  });
});
