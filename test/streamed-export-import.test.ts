/**
 * Exports and imports streamed, so Workspaces whose files add up to more than fits in memory round-trip (#209).
 * The files are generated as they are sent rather than held, and every transfer streams over real HTTP, so the
 * test's own memory stays flat and what grows is the server's.
 */

const MB = 1024 * 1024;

/** `size` bytes that don't compress, the same for the same `seed`, generated as they are read. */
function generated(seed: number, size: number): Readable {
  const cipher = createCipheriv("aes-256-ctr", Buffer.alloc(32, seed), Buffer.alloc(16));
  const zeros = Buffer.alloc(MB);
  let left = size;
  return new Readable({
    read() {
      if (left === 0) return void this.push(null);
      const n = Math.min(left, zeros.length);
      left -= n;
      this.push(cipher.update(zeros.subarray(0, n)));
    },
  });
}

/** The SHA-256 of everything `stream` gives. */
async function sha256(stream: Readable): Promise<string> {
  const hash = createHash("sha256");
  for await (const chunk of stream) hash.update(chunk as Buffer);
  return hash.digest("hex");
}

/** Everything `stream` gives, as text. */
async function text(stream: Readable): Promise<string> {
  let all = "";
  for await (const chunk of stream) all += String(chunk);
  return all;
}

/** A temporary file path, removed when the test ends. */
async function tempFile(name: string): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "cronk-streamed-"));
  onTestFinished(() => rm(dir, { recursive: true, force: true }));
  return join(dir, name);
}

/** Uploads `size` generated bytes from `seed` as an Attachment at `path`, streamed. */
async function attach(client: Client, path: string, seed: number, size: number) {
  const res = await client.send(path, { method: "POST", body: generated(seed, size), headers: { "content-type": "application/octet-stream" } });
  expect(res.statusCode).toBe(201);
  return (JSON.parse(await text(res)) as { attachment: { id: string } }).attachment;
}

/**
 * Runs `work` while sampling how many bytes of Buffers the process holds beyond what it held before, and answers
 * the most it saw. The server runs in this process, so this counts what it holds.
 */
async function peakBuffers(work: () => Promise<void>): Promise<number> {
  const held = () => process.memoryUsage().arrayBuffers;
  const before = held();
  let peak = 0;
  const sampling = setInterval(() => (peak = Math.max(peak, held() - before)), 5);
  try {
    await work();
  } finally {
    clearInterval(sampling);
  }
  return Math.max(peak, held() - before);
}

describe("a Workspace export holding more than 200 MB of Attachments", () => {
  it("is streamed out and back into a fresh installation, every Attachment downloading byte for byte", { timeout: 300_000 }, async () => {
    const { admin } = await startInstalledCronk();
    await admin.post("/api/projects", { name: "Cronk", key: "CRONK" });
    await admin.post("/api/projects/CRONK/tickets", { title: "Recordings" });
    const sizes = [75 * MB, 75 * MB, 75 * MB + 123];
    const attached = [];
    for (const [i, size] of sizes.entries()) attached.push({ ...(await attach(admin, `/api/tickets/CRONK-1/attachments?name=recording-${i}.bin`, i + 1, size)), seed: i + 1, size });

    const archive = await tempFile("export.tar.gz");
    const exportPeak = await peakBuffers(async () => {
      const res = await admin.send("/api/export");
      expect(res.statusCode).toBe(200);
      await pipeline(res, createWriteStream(archive));
    });
    // Holding even one of the files whole would take more.
    expect(exportPeak).toBeLessThan(64 * MB);

    const elsewhere = (await startInstalledCronk("Elsewhere")).admin;
    const importPeak = await peakBuffers(async () => {
      const imported = await elsewhere.send("/api/import", { method: "POST", body: createReadStream(archive), headers: { "content-type": "application/gzip" } });
      expect(imported.statusCode, await text(imported)).toBe(201);
    });
    expect(importPeak).toBeLessThan(64 * MB);

    const { attachments } = (await elsewhere.get("/api/tickets/CRONK-1/attachments")).body;
    expect(attachments.map((a: { id: string; size: number }) => [a.id, a.size])).toEqual(attached.map((a) => [a.id, a.size]));
    for (const a of attached) {
      const file = await elsewhere.send(`/api/attachments/${a.id}/file`);
      expect(file.statusCode).toBe(200);
      expect(await sha256(file)).toBe(await sha256(generated(a.seed, a.size)));
    }
    expect((await elsewhere.get("/api/workspace/storage")).body.attachments).toEqual({ files: 3, bytes: sizes.reduce((a, b) => a + b) });
  });
});

/** Bytes of every value, so a file that isn't text, or is mangled as text, shows. */
const binary = (n: number) => Buffer.from(Array.from({ length: n }, (_, i) => (i * 7) % 256));

/**
 * A Workspace with Attachments on a Ticket, a Document, a Report and a Comment, and a Project Artifact at two Versions
 * holding a picture and a Markdown file; answers how to read each file back, by what it is.
 */
async function workspaceWithFiles() {
  const { cronk, admin } = await startInstalledCronk();
  await admin.post("/api/projects", { name: "Cronk", key: "CRONK" });
  await admin.post("/api/projects/CRONK/tickets", { title: "Build it" });
  const files: { name: string; read: string; bytes: Buffer }[] = [];
  const attachTo = async (client: Client, path: string, name: string, bytes: Buffer) => {
    const res = await client.upload(`${path}/attachments?name=${name}`, bytes, "application/octet-stream");
    expect(res.status).toBe(201);
    files.push({ name, read: `/api/attachments/${res.body.attachment.id}/file`, bytes });
  };
  await attachTo(admin, "/api/tickets/CRONK-1", "trace.bin", binary(3000));
  const guide = (await admin.post("/api/projects/CRONK/documents", { title: "Guide" })).body.document;
  await attachTo(admin, `/api/documents/${guide.id}`, "notes.md", Buffer.from("# Notes\n\nKept as written.\n"));
  const comment = (await admin.post(`/api/documents/${guide.id}/comments`, { body: "Here." })).body.comment;
  await attachTo(admin, `/api/comments/${comment.id}`, "map.png", binary(500));

  const ada = (await admin.get("/api/me")).body.user;
  const { secret } = await registerAgent(admin, "claude-laptop");
  await admin.patch("/api/tickets/CRONK-1", { delegateId: (await admin.get("/api/agents")).body.agents[0].id, assigneeId: ada.id });
  const agent = await startSession(cronk, secret);
  expect((await agent.post("/api/tickets/CRONK-1/claim")).status).toBe(200);
  const report = (await agent.post("/api/tickets/CRONK-1/reports", { title: "Findings", body: "It was the cache." })).body.report;
  await attachTo(agent, `/api/documents/${report.id}`, "profile.bin", binary(1234));

  const { artifact } = (await admin.upload("/api/projects/CRONK/artifacts?title=Limits", await tarGz({ "index.html": "<p>v1</p>" }))).body;
  await admin.upload(`/api/artifacts/${artifact.id}/versions?baseVersion=1`, await tarGz({ "index.html": "<p>v2</p>", "img/chart.png": "\u0089PNG\u0000\u00ff", "README.md": "# Limits\n" }));
  return { admin, files, artifact };
}

/** The file at `path` of the latest Version of Artifact `id`, as `client`'s installation serves it. */
async function artifactFile(client: Client, id: string, path: string): Promise<Buffer> {
  const { artifact } = (await client.get(`/api/artifacts/${id}`)).body;
  const res = await client.download(`${new URL(artifact.frameUrl).pathname}${path}`, { host: ARTIFACT_HOST });
  expect(res.status, path).toBe(200);
  return res.body;
}

describe("an export's Attachments and Artifact files", () => {
  it("round-trip through the streamed export and import: Document, Report and Comment Attachments and every Artifact Version's files", async () => {
    const { admin, files, artifact } = await workspaceWithFiles();
    const exported = await admin.download("/api/export");

    const elsewhere = (await startInstalledCronk("Elsewhere")).admin;
    const imported = await elsewhere.upload("/api/import", exported.body);
    expect(imported.status, JSON.stringify(imported.body)).toBe(201);

    for (const file of files) {
      const res = await elsewhere.download(file.read);
      expect(res.status, file.name).toBe(200);
      expect(res.body.equals(file.bytes), file.name).toBe(true);
    }
    const moved = (await elsewhere.get(`/api/artifacts/${artifact.id}`)).body.artifact;
    expect(moved.versions.map((v: { number: number }) => v.number)).toEqual([2, 1]);
    for (const path of ["index.html", "img/chart.png", "README.md"]) {
      expect((await artifactFile(elsewhere, artifact.id, path)).equals(await artifactFile(admin, artifact.id, path)), path).toBe(true);
    }
    expect((await artifactFile(elsewhere, artifact.id, "README.md")).toString()).toBe("# Limits\n");
    expect((await elsewhere.get("/api/workspace/storage")).body).toEqual((await admin.get("/api/workspace/storage")).body);
  });
});

/** The files of a gzipped tar archive, path to bytes, in order. */
async function untarFiles(archive: Buffer): Promise<Map<string, Buffer>> {
  const extract = tar.extract();
  const files = new Map<string, Buffer>();
  const done = (async () => {
    for await (const entry of extract) {
      const chunks: Buffer[] = [];
      for await (const chunk of entry) chunks.push(Buffer.from(chunk as Uint8Array));
      files.set(entry.header.name, Buffer.concat(chunks));
    }
  })();
  extract.end(gunzipSync(archive));
  await done;
  return files;
}

/** A tar archive of `files`, gzipped unless `plain`. */
async function tarFiles(files: Map<string, Buffer | string>, { plain = false } = {}): Promise<Buffer> {
  const pack = tar.pack();
  for (const [name, contents] of files) pack.entry({ name }, contents);
  pack.finalize();
  const chunks: Buffer[] = [];
  for await (const chunk of pack) chunks.push(Buffer.from(chunk as Uint8Array));
  return plain ? Buffer.concat(chunks) : gzipSync(Buffer.concat(chunks));
}

/** `file`, a Markdown file with frontmatter, with its frontmatter changed by `edit`. */
function editFrontmatter(file: Buffer, edit: (data: any) => void): string {
  const match = /^---\n([\s\S]*?\n)?---\n/.exec(file.toString())!;
  const data = parse(match[1] ?? "");
  edit(data);
  return `---\n${stringify(data)}---\n${file.toString().slice(match[0].length)}`;
}

/** An installation keeping its files in a directory the test can look into, and the files there. */
async function installationWithFilesIn(name: string) {
  const dir = await mkdtemp(join(tmpdir(), "cronk-files-"));
  onTestFinished(() => rm(dir, { recursive: true, force: true }));
  const { admin } = await startInstalledCronk(name, { storage: { kind: "disk", dir } });
  const stored = async () => (await readdir(dir, { recursive: true, withFileTypes: true })).filter((e) => e.isFile()).map((e) => e.name);
  return { admin, stored, dir };
}

describe("an import that fails partway", () => {
  it("leaves no Attachments, Artifacts or files behind, and the same export imports afterwards", async () => {
    const { admin } = await workspaceWithFiles();
    const exported = (await admin.download("/api/export")).body;
    // Ticket Attachments are imported after Documents', and Artifacts after Tickets, so files have been stored by the time this one is missed.
    const files = await untarFiles(exported);
    const index = "projects/CRONK/tickets/CRONK-1.attachments/index.md";
    const edited = new Map<string, Buffer | string>(files);
    edited.set(index, editFrontmatter(files.get(index)!, (data) => (data.attachments[0].file = "9-missing.bin")));

    const elsewhere = await installationWithFilesIn("Elsewhere");
    const res = await elsewhere.admin.upload("/api/import", await tarFiles(edited));
    expect(res.status).toBe(400);
    expect(res.body.error).toContain("projects/CRONK/tickets/CRONK-1.attachments/9-missing.bin");

    expect(await elsewhere.stored()).toEqual([]);
    expect((await elsewhere.admin.get("/api/workspace/storage")).body).toEqual({ attachments: { files: 0, bytes: 0 }, artifacts: { files: 0, bytes: 0 } });
    expect((await elsewhere.admin.get("/api/projects/CRONK")).status).toBe(404);

    expect((await elsewhere.admin.upload("/api/import", exported)).status).toBe(201);
    expect((await elsewhere.admin.get("/api/workspace/storage")).body).toEqual((await admin.get("/api/workspace/storage")).body);
    expect(await elsewhere.stored()).toHaveLength(4 + 4);
  });
});

describe("a file larger than the import allows", () => {
  it("refuses a Workspace export with a 413 naming it when it is over the Attachment limit the export's own workspace.md sets", async () => {
    const { admin } = await startInstalledCronk();
    await admin.post("/api/projects", { name: "Cronk", key: "CRONK" });
    await admin.post("/api/projects/CRONK/tickets", { title: "Build it" });
    expect((await admin.upload("/api/tickets/CRONK-1/attachments?name=dump.bin", binary(1.5 * MB), "application/octet-stream")).status).toBe(201);
    const files = await untarFiles((await admin.download("/api/export")).body);
    const edited = new Map<string, Buffer | string>(files);
    edited.set("workspace.md", editFrontmatter(files.get("workspace.md")!, (data) => (data.attachmentMaxBytes = MB)));

    const elsewhere = await installationWithFilesIn("Elsewhere");
    const res = await elsewhere.admin.upload("/api/import", await tarFiles(edited));
    expect(res.status).toBe(413);
    expect(res.body.error).toBe("projects/CRONK/tickets/CRONK-1.attachments/1-dump.bin is larger than 1 MB, the most an Attachment may take in this Workspace");
    expect(await elsewhere.stored()).toEqual([]);
  });

  it("refuses a Project export with a 413 naming it when it is over this Workspace's limits, before storing it whole", async () => {
    const { admin } = await startInstalledCronk();
    await admin.post("/api/projects", { name: "Cronk", key: "CRONK" });
    await admin.post("/api/projects/CRONK/tickets", { title: "Build it" });
    expect((await admin.upload("/api/tickets/CRONK-1/attachments?name=dump.bin", binary(1.5 * MB), "application/octet-stream")).status).toBe(201);
    const exported = (await admin.download("/api/projects/CRONK/export")).body;

    const elsewhere = await installationWithFilesIn("Elsewhere");
    expect((await elsewhere.admin.patch("/api/workspace", { attachmentMaxBytes: MB, artifactMaxBytes: MB })).status).toBe(200);
    const res = await elsewhere.admin.upload("/api/import", exported);
    expect(res.status).toBe(413);
    expect(res.body.error).toBe("projects/CRONK/tickets/CRONK-1.attachments/1-dump.bin is larger than 1 MB, the most an Attachment may take in this Workspace");
  });

  it("refuses an Artifact file over this Workspace's Artifact Version limit with a 413 naming it, whatever it is named", async () => {
    const { admin } = await startInstalledCronk();
    await admin.post("/api/projects", { name: "Cronk", key: "CRONK" });
    await admin.upload("/api/projects/CRONK/artifacts?title=Limits", await tarGz({ "index.html": "<p>v1</p>", "notes.md": "#".repeat(1.5 * MB) }));
    const exported = (await admin.download("/api/projects/CRONK/export")).body;

    const elsewhere = await installationWithFilesIn("Elsewhere");
    expect((await elsewhere.admin.patch("/api/workspace", { attachmentMaxBytes: 2 * MB, artifactMaxBytes: MB })).status).toBe(200);
    const res = await elsewhere.admin.upload("/api/import", exported);
    expect(res.status).toBe(413);
    expect(res.body.error).toBe("projects/CRONK/artifacts/1-limits/1/notes.md is larger than 1 MB, the most an Artifact Version may take in this Workspace");
    expect(await elsewhere.stored()).toEqual([]);
    expect(await elsewhere.stored()).toEqual([]);
  });

  it("refuses an Artifact Version holding more files than this Workspace allows one, as publishing it would be", async () => {
    const { admin } = await workspaceWithFiles();
    const exported = (await admin.download("/api/projects/CRONK/export")).body;

    const elsewhere = await installationWithFilesIn("Elsewhere");
    expect((await elsewhere.admin.patch("/api/workspace", { artifactMaxFiles: 2 })).status).toBe(200);
    const res = await elsewhere.admin.upload("/api/import", exported);
    expect(res.status).toBe(413);
    expect(res.body.error).toContain("projects/CRONK/artifacts/1-limits/2/ holds 3 files, more than the 2");
    expect(await elsewhere.stored()).toEqual([]);
  });
});

describe("an export archived again by hand", () => {
  it.each([
    ["a zip archive, deflated", (files: Map<string, Buffer>) => zip(Object.fromEntries([...files].map(([p, b]) => [`export/${p}`, b])))],
    ["a zip archive, stored", (files: Map<string, Buffer>) => zip(Object.fromEntries([...files].map(([p, b]) => [`export/${p}`, b])), { stored: true })],
    ["a plain tar archive", (files: Map<string, Buffer>) => tarFiles(new Map([...files].map(([p, b]) => [`export/${p}`, b])), { plain: true })],
    ["a gzipped tar archive, its files in another order", (files: Map<string, Buffer>) => tarFiles(new Map([...files].reverse()))],
  ])("imports as %s, every file kept byte for byte", async (_kind, archive) => {
    const { admin, files } = await workspaceWithFiles();
    const exported = await untarFiles((await admin.download("/api/export")).body);

    const elsewhere = await installationWithFilesIn("Elsewhere");
    const res = await elsewhere.admin.upload("/api/import", await archive(exported), "application/octet-stream");
    expect(res.status, JSON.stringify(res.body)).toBe(201);

    for (const file of files) expect((await elsewhere.admin.download(file.read)).body.equals(file.bytes), file.name).toBe(true);
    expect((await elsewhere.admin.get("/api/workspace/storage")).body).toEqual((await admin.get("/api/workspace/storage")).body);
    expect(await elsewhere.stored()).toHaveLength(4 + 4);
  });
});

describe("an import whose connection drops partway", () => {
  it("leaves no files behind, and the same export imports afterwards", async () => {
    const { admin } = await startInstalledCronk();
    await admin.post("/api/projects", { name: "Cronk", key: "CRONK" });
    await admin.post("/api/projects/CRONK/tickets", { title: "Recordings" });
    await attach(admin, "/api/tickets/CRONK-1/attachments?name=first.bin", 1, 2 * MB);
    await attach(admin, "/api/tickets/CRONK-1/attachments?name=second.bin", 2, 4 * MB);
    const exported = (await admin.download("/api/export")).body;

    const elsewhere = await installationWithFilesIn("Elsewhere");
    // Sends the first file and half the second, then the connection drops.
    const cut = exported.length - 2 * MB;
    let sent = false;
    const dropping = new Readable({
      read() {
        if (sent) return;
        sent = true;
        this.push(exported.subarray(0, cut));
        setTimeout(() => this.destroy(new Error("connection dropped")), 200);
      },
    });
    await expect(elsewhere.admin.send("/api/import", { method: "POST", body: dropping, headers: { "content-type": "application/gzip" } })).rejects.toThrow();

    await expect.poll(() => elsewhere.stored(), { timeout: 5_000 }).toEqual([]);
    expect((await elsewhere.admin.get("/api/workspace/storage")).body.attachments).toEqual({ files: 0, bytes: 0 });
    expect((await elsewhere.admin.upload("/api/import", exported)).status).toBe(201);
    expect(await elsewhere.stored()).toHaveLength(2);
  });
});

